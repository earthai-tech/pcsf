"""Tiny synthetic solver runs shipped with pcsf.

The runs exercise the native parsers and adapters in examples,
tests and the conformance suite. They are synthetic, a few hundred
bytes each, and regenerated by ``tools/make_tiny_datasets.py``.

``occam2d_tiny``
    Occam2D mesh with padding and one air row, model, data,
    two iterations and a log file.
``modem_tiny``
    ModEM 3-D ``.rho`` model with an origin trailer and air fill,
    a data file whose ``Z`` column is a depth, and an NLCG log.
``mare2dem_tiny``
    MARE2DEM ``.poly``, ``.resistivity`` and log files, with the
    triangulation as plain text (``tiny.node.txt``,
    ``tiny.ele.txt``) so that Triangle is not needed.
"""

from __future__ import annotations

from pathlib import Path

__all__ = ["NAMES", "path"]

#: Names of the bundled runs.
NAMES = ("occam2d_tiny", "modem_tiny", "mare2dem_tiny")

_HERE = Path(__file__).resolve().parent


def path(name: str) -> Path:
    """Folder of a bundled run.

    Parameters
    ----------
    name : str
        One of :data:`NAMES`.

    Returns
    -------
    pathlib.Path
        Existing folder inside the installed package.

    Raises
    ------
    KeyError
        If *name* is not a bundled run.

    Examples
    --------
    >>> import pcsf
    >>> run = pcsf.datasets.path("modem_tiny")
    >>> sorted(p.name for p in run.iterdir())
    ['tiny.dat', 'tiny_NLCG.log', 'tiny_NLCG_002.rho']
    """
    if name not in NAMES:
        raise KeyError(f"unknown dataset {name!r}; known: {NAMES}")
    return _HERE / name
