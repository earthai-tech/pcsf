"""Parsers of MARE2DEM files.

MARE2DEM [1]_ describes a 2-D model as a planar straight-line graph
(``.poly``, Triangle format [2]_) whose regions carry one parameter
each; every iteration writes a ``.resistivity`` table with one row
per region. The mesh itself is generated by Triangle at run time,
so converting a result needs either the triangulation or the
Triangle program (:func:`triangulate_poly`, ``pcsf[mare2dem]``).

References
----------
.. [1] Key, K., 2016, MARE2DEM: a 2-D inversion code for
   controlled-source electromagnetic and magnetotelluric data:
   Geophysical Journal International, 207, 571-588.
.. [2] Shewchuk, J. R., 1996, Triangle: Engineering a 2D quality
   mesh generator and Delaunay triangulator, in Applied
   Computational Geometry: Towards Geometric Engineering, Lecture
   Notes in Computer Science 1148: Springer, 203-222.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass, field

import numpy as np

from ..compat.optional import import_optional
from ..exceptions import FormatError
from ._tokens import header_value, read_lines

__all__ = [
    "Mare2demLog",
    "Mare2demResistivity",
    "PolyFile",
    "read_log",
    "read_poly",
    "read_resistivity",
    "triangulate_poly",
]


@dataclass
class Mare2demResistivity:
    """A MARE2DEM ``.resistivity`` table.

    Attributes
    ----------
    rho : ndarray of shape (n_regions, k)
        Resistivity of each region, ohm m; ``k`` is 1 for isotropic
        models and up to 3 for anisotropic ones.
    free : ndarray of int, shape (n_regions, k)
        Parameter number of each value, 0 when fixed.
    anisotropy : str
        Declared anisotropy, such as ``"isotropic"``.
    header : dict
        Every ``Key: value`` header line, keys in upper case.
    """

    rho: np.ndarray
    free: np.ndarray
    anisotropy: str = "isotropic"
    header: dict[str, str] = field(default_factory=dict)

    @property
    def misfit(self) -> float:
        """``Model Misfit`` of the header, NaN when absent."""
        try:
            return float(self.header.get("MODEL MISFIT", "nan"))
        except ValueError:
            return float("nan")


@dataclass
class PolyFile:
    """Planar straight-line graph of a Triangle ``.poly`` file.

    Attributes
    ----------
    nodes : ndarray of shape (n, 2)
        Vertex coordinates (y along the profile, z down), metres.
    segments : ndarray of int, shape (m, 2)
        1-based vertex indices of each segment, as in the file.
    holes : ndarray of shape (h, 2)
        Hole points.
    regions : ndarray of shape (r, 4)
        ``x, y, attribute, max_area`` of each region point; the
        attribute is the 1-based region number.
    """

    nodes: np.ndarray
    segments: np.ndarray
    holes: np.ndarray
    regions: np.ndarray


@dataclass
class Mare2demLog:
    """Iteration history of a MARE2DEM log file.

    Attributes
    ----------
    iteration : ndarray of int
    rms, roughness, mu : ndarray of float
        Misfit, roughness and optimal Lagrange multiplier
        (log10 mu) of each completed iteration.
    converged : bool
        True when a convergence status of 1 was reported.
    """

    iteration: np.ndarray
    rms: np.ndarray
    roughness: np.ndarray
    mu: np.ndarray
    converged: bool = False


def read_resistivity(
    path: str | os.PathLike[str],
) -> Mare2demResistivity:
    """Read a MARE2DEM ``.resistivity`` file.

    Parameters
    ----------
    path : str or os.PathLike
        File such as ``demo.6.resistivity``.

    Returns
    -------
    Mare2demResistivity

    Raises
    ------
    FormatError
        If the region count is missing or the table is incomplete.

    Notes
    -----
    Each region row holds its number, :math:`k` resistivities,
    :math:`k` parameter numbers, then bounds, prejudice and weights,
    with :math:`k = 1` for ``isotropic``, 2 for ``isotropic_ip`` or
    ``triaxial`` pairs and 3 for ``triaxial``.

    Examples
    --------
    >>> import os, tempfile
    >>> from pcsf.native.mare2dem import read_resistivity
    >>> text = ("Format: MARE2DEM_1.1\\nAnisotropy: isotropic\\n"
    ...         "Number of regions: 2\\n1 10.0 1 0 0 0 0\\n"
    ...         "2 1e12 0 0 0 0 0\\n")
    >>> with tempfile.TemporaryDirectory() as tmp:
    ...     p = os.path.join(tmp, "m.1.resistivity")
    ...     _ = open(p, "w").write(text)
    ...     r = read_resistivity(p)
    >>> r.rho[:, 0].tolist(), r.free[:, 0].tolist()
    ([10.0, 1000000000000.0], [1, 0])
    """
    lines = read_lines(path)
    header: dict[str, str] = {}
    i = 0
    n_regions = None
    while i < len(lines):
        text = lines[i].strip()
        i += 1
        kv = header_value(text)
        if kv is None:
            continue
        header[kv[0]] = kv[1]
        if kv[0] == "NUMBER OF REGIONS":
            n_regions = int(kv[1])
            break
    if n_regions is None:
        raise FormatError(f"{path}: no 'Number of regions' line")
    aniso = header.get("ANISOTROPY", "isotropic").strip().lower()
    k = {"isotropic": 1, "isotropic_ip": 2, "triaxial": 3}.get(aniso)
    k = k or 2
    rows: list[list[float]] = []
    for raw in lines[i:]:
        text = raw.strip()
        if not text or text.startswith(("!", "#")):
            continue
        rows.append([float(v) for v in text.split()])
        if len(rows) == n_regions:
            break
    if len(rows) != n_regions:
        raise FormatError(
            f"{path}: expected {n_regions} regions, got {len(rows)}"
        )
    width = min(len(r) for r in rows)
    if width < 1 + 2 * k:
        raise FormatError(f"{path}: region rows too short")
    arr = np.array([r[: 1 + 2 * k] for r in rows], dtype=float)
    return Mare2demResistivity(
        rho=arr[:, 1 : 1 + k],
        free=arr[:, 1 + k : 1 + 2 * k].astype(np.int64),
        anisotropy=aniso,
        header=header,
    )


def _data_lines(lines: list[str]) -> list[list[str]]:
    out = []
    for raw in lines:
        text = raw.split("#", 1)[0].strip()
        if text:
            out.append(text.split())
    return out


def read_poly(path: str | os.PathLike[str]) -> PolyFile:
    """Read a Triangle ``.poly`` file.

    Parameters
    ----------
    path : str or os.PathLike
        ``.poly`` file with its vertices inline (vertex count > 0).

    Returns
    -------
    PolyFile

    Raises
    ------
    FormatError
        If a section is truncated or the vertices are stored in a
        separate ``.node`` file.

    Examples
    --------
    >>> import os, tempfile
    >>> from pcsf.native.mare2dem import read_poly
    >>> text = ("3 2 0 0\\n1 0 0\\n2 1 0\\n3 0 1\\n3 0\\n1 1 2\\n"
    ...         "2 2 3\\n3 3 1\\n0\\n1\\n1 0.2 0.2 1 -1\\n")
    >>> with tempfile.TemporaryDirectory() as tmp:
    ...     p = os.path.join(tmp, "m.poly")
    ...     _ = open(p, "w").write(text)
    ...     poly = read_poly(p)
    >>> poly.nodes.shape, poly.segments.shape, poly.regions.tolist()
    ((3, 2), (3, 2), [[0.2, 0.2, 1.0, -1.0]])
    """
    rows = _data_lines(read_lines(path))
    pos = 0

    def take(n: int, what: str) -> list[list[str]]:
        nonlocal pos
        if pos + n > len(rows):
            raise FormatError(f"{path}: truncated {what} section")
        block = rows[pos : pos + n]
        pos += n
        return block

    head = take(1, "vertex")[0]
    n_nodes = int(head[0])
    if n_nodes == 0:
        raise FormatError(
            f"{path}: vertices are in a separate .node file"
        )
    nodes = np.array(
        [[float(r[1]), float(r[2])] for r in take(n_nodes, "vertex")]
    )
    n_seg = int(take(1, "segment")[0][0])
    segments = np.array(
        [
            [int(float(r[1])), int(float(r[2]))]
            for r in take(n_seg, "segment")
        ],
        dtype=np.int64,
    ).reshape(-1, 2)
    holes = np.zeros((0, 2))
    regions = np.zeros((0, 4))
    if pos < len(rows):
        n_holes = int(take(1, "hole")[0][0])
        holes = np.array(
            [[float(r[1]), float(r[2])] for r in take(n_holes, "hole")]
        ).reshape(-1, 2)
    if pos < len(rows):
        n_reg = int(take(1, "region")[0][0])
        regions = np.array(
            [[float(v) for v in r[1:5]] for r in take(n_reg, "region")]
        ).reshape(-1, 4)
    return PolyFile(nodes, segments, holes, regions)


def triangulate_poly(
    poly: PolyFile,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Triangulate a ``.poly`` graph as MARE2DEM does.

    Parameters
    ----------
    poly : PolyFile
        Graph read by :func:`read_poly`.

    Returns
    -------
    nodes : ndarray of shape (n, 2)
        Vertices, metres.
    triangles : ndarray of int, shape (m, 3)
        0-based vertex indices.
    region_ids : ndarray of int, shape (m,)
        1-based region number of each triangle.

    Raises
    ------
    MissingDependencyError
        If the ``triangle`` package is not installed
        (``pip install "pcsf[mare2dem]"``).

    Notes
    -----
    Triangle runs with switches ``p`` (keep the input segments) and
    ``A`` (assign region attributes), which reproduces the regions of
    MARE2DEM's own call without adding quality refinement.
    """
    triangle = import_optional("triangle", feature="MARE2DEM meshes")
    spec = {"vertices": poly.nodes, "segments": poly.segments - 1}
    if poly.regions.size:
        spec["regions"] = poly.regions
    if poly.holes.size:
        spec["holes"] = poly.holes
    tri = triangle.triangulate(spec, "pA")
    attrs = np.asarray(
        tri.get("triangle_attributes", np.zeros((0, 1)))
    )
    region_ids = np.round(attrs.ravel()).astype(np.int64)
    return (
        np.asarray(tri["vertices"], dtype=float),
        np.asarray(tri["triangles"], dtype=np.int64),
        region_ids,
    )


_ITER = re.compile(r"\*\*\s+Iteration\s+(\d+)\s+\*\*")
_FIELDS = {
    "rms": re.compile(r"Model Misfit\s*:\s*([\d.eE+\-]+)"),
    "roughness": re.compile(r"Roughness\s*:\s*([\d.eE+\-]+)"),
    "mu": re.compile(r"Optimal Mu\s*:\s*([\d.eE+\-]+)"),
}
_CONV = re.compile(r"Convergence Status\s*:\s*(\d+)")
_CONVERGED_TEXT = (
    "target misfit achieved",
    "misfit reached",
    "converged",
)


def read_log(path: str | os.PathLike[str]) -> Mare2demLog:
    """Read the iteration history of a MARE2DEM log file.

    Parameters
    ----------
    path : str or os.PathLike
        ``.logfile`` written by MARE2DEM.

    Returns
    -------
    Mare2demLog
        One entry per iteration that reports a misfit; missing
        roughness or mu are 0, as in pyCSAMT.

    Examples
    --------
    >>> import os, tempfile
    >>> from pcsf.native.mare2dem import read_log
    >>> text = ("** Iteration     1 **\\n Model Misfit: 6.9\\n"
    ...         " Roughness: 1.4\\n Optimal Mu: 4.0\\n"
    ...         " Convergence Status: 1\\n")
    >>> with tempfile.TemporaryDirectory() as tmp:
    ...     p = os.path.join(tmp, "m.logfile")
    ...     _ = open(p, "w").write(text)
    ...     log = read_log(p)
    >>> log.rms.tolist(), log.converged
    ([6.9], True)
    """
    records: list[dict[str, float]] = []
    current: dict[str, float] | None = None
    converged = False

    def flush() -> None:
        if current is not None and "rms" in current:
            records.append(current)

    for line in read_lines(path):
        m = _ITER.search(line)
        if m:
            flush()
            current = {"iteration": int(m.group(1))}
            continue
        m = _CONV.search(line)
        if m:
            converged = converged or int(m.group(1)) == 1
        low = line.lower()
        if any(s in low for s in _CONVERGED_TEXT):
            converged = True
        if current is None:
            continue
        for name, pattern in _FIELDS.items():
            m = pattern.search(line)
            if m:
                current[name] = float(m.group(1))
    flush()
    return Mare2demLog(
        iteration=np.array([r["iteration"] for r in records], int),
        rms=np.array([r["rms"] for r in records], float),
        roughness=np.array(
            [r.get("roughness", 0.0) for r in records], float
        ),
        mu=np.array([r.get("mu", 0.0) for r in records], float),
        converged=converged,
    )
